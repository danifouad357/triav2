export function getMobileInterpolatedCorners(activeFrame: number) {
  const totalFrames = mobileTrackingData.length;
  if (totalFrames === 0) return null;
  
  const frameIndex = Math.floor(activeFrame);
  const nextFrameIndex = Math.min(frameIndex + 1, totalFrames - 1);
  const fraction = activeFrame - frameIndex;

  const current = mobileTrackingData[Math.min(frameIndex, totalFrames - 1)];
  const next = mobileTrackingData[nextFrameIndex];

  return current.map((pt, i) => [
    (pt.x + (next[i].x - pt.x) * fraction) * 1080,
    (pt.y + (next[i].y - pt.y) * fraction) * 1920
  ]) as [[number, number], [number, number], [number, number], [number, number]];
}
